-- 1. TABLE DES ÉTUDIANTS (BTS 2 Génie Civil - Géomètre Topographe)
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT DEFAULT '',
    classe TEXT NOT NULL DEFAULT 'BTS 2 - GC-GT',
    ecole TEXT DEFAULT 'Yamoussoukro',
    registered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status TEXT NOT NULL DEFAULT 'pending', -- 'pending' | 'active' | 'expired'
    student_code TEXT UNIQUE,
    confirmed_at TIMESTAMPTZ,
    valid_until TIMESTAMPTZ,
    last_payment_month TEXT,
    visits INTEGER NOT NULL DEFAULT 0,
    posts_count INTEGER NOT NULL DEFAULT 0
);

-- 2. TABLE DES SUPPORTS DE COURS & CORRIGÉS PDF
CREATE TABLE IF NOT EXISTS public.resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL, -- 'cours' | 'exercice_corrige'
    classe TEXT NOT NULL DEFAULT 'BTS 2 - GC-GT',
    subject TEXT DEFAULT '',
    filename TEXT NOT NULL,
    url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. TABLE DES SUJETS DU FORUM ACADÉMIQUE
CREATE TABLE IF NOT EXISTS public.forum_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name TEXT NOT NULL,
    author_classe TEXT NOT NULL DEFAULT 'BTS 2 - GC-GT',
    author_role TEXT NOT NULL DEFAULT 'etudiant', -- 'etudiant' | 'admin'
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. TABLE DES RÉPONSES DU FORUM ACADÉMIQUE
CREATE TABLE IF NOT EXISTS public.forum_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES public.forum_posts(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL,
    author_classe TEXT NOT NULL DEFAULT 'BTS 2 - GC-GT',
    author_role TEXT NOT NULL DEFAULT 'etudiant',
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. TABLE DE LA MESSAGERIE ADMINISTRATEUR (Notifications d'inscriptions & demandes)
CREATE TABLE IF NOT EXISTS public.mailbox_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name TEXT NOT NULL,
    sender_email TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);

-- =============================================================================
-- POLITIQUES DE SÉCURITÉ (Row Level Security - RLS) POUR LE PORTAIL WEB
-- =============================================================================
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.resources ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forum_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forum_replies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mailbox_messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acces public complet students" ON public.students;
CREATE POLICY "Acces public complet students" ON public.students
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acces public complet resources" ON public.resources;
CREATE POLICY "Acces public complet resources" ON public.resources
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acces public complet forum_posts" ON public.forum_posts;
CREATE POLICY "Acces public complet forum_posts" ON public.forum_posts
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acces public complet forum_replies" ON public.forum_replies;
CREATE POLICY "Acces public complet forum_replies" ON public.forum_replies
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acces public complet mailbox_messages" ON public.mailbox_messages;
CREATE POLICY "Acces public complet mailbox_messages" ON public.mailbox_messages
    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

-- =============================================================================
-- BUCKET DE STOCKAGE SUPABASE POUR LES NOUVEAUX COURS PDF ("pdfs")
-- =============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('pdfs', 'pdfs', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Lecture publique des PDF" ON storage.objects;
CREATE POLICY "Lecture publique des PDF" ON storage.objects
    FOR SELECT TO anon, authenticated USING (bucket_id = 'pdfs');

DROP POLICY IF EXISTS "Upload public des PDF" ON storage.objects;
CREATE POLICY "Upload public des PDF" ON storage.objects
    FOR INSERT TO anon, authenticated WITH CHECK (bucket_id = 'pdfs');

DROP POLICY IF EXISTS "Suppression publique des PDF" ON storage.objects;
CREATE POLICY "Suppression publique des PDF" ON storage.objects
    FOR DELETE TO anon, authenticated USING (bucket_id = 'pdfs');

